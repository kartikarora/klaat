package me.kartikarora.klaat

import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.Timeout
import org.junit.jupiter.api.io.TempDir
import java.io.File
import java.net.HttpURLConnection
import java.net.URI
import java.nio.file.Path
import java.util.concurrent.TimeUnit
import kotlin.concurrent.thread
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class ServeDirectoryListingTemplateTest {

    @TempDir
    lateinit var tempDir: Path

    @BeforeEach
    fun setUp() {
        // Create some files and directories
        val subDir = tempDir.resolve("subdir").toFile()
        subDir.mkdirs()
        tempDir.resolve("test-file.txt").toFile().writeText("Hello World")
    }

    @Test
    @Timeout(value = 15, unit = TimeUnit.SECONDS)
    fun `test directory listing uses beautiful template`() {
        val port = 9093
        val host = "localhost"
        
        var serverThread: Thread? = null
        var serverStarted = false
        
        try {
            serverThread = thread {
                val args = arrayOf(
                    "serve",
                    "-addr", "$host:$port",
                    "-d", tempDir.toFile().absolutePath,
                    "--no-browser"
                )
                main(args)
            }

            // Wait for server to start
            var attempts = 0
            val maxAttempts = 30
            while (!serverStarted && attempts < maxAttempts) {
                Thread.sleep(100)
                try {
                    val url = URI("http://$host:$port/").toURL()
                    val connection = url.openConnection() as HttpURLConnection
                    connection.requestMethod = "GET"
                    val responseCode = connection.responseCode
                    if (responseCode == 200) {
                        serverStarted = true
                    }
                    connection.disconnect()
                } catch (e: Exception) {
                }
                attempts++
            }

            assertTrue(serverStarted, "Server should start successfully")

            // Fetch directory listing
            val url = URI("http://$host:$port/").toURL()
            val connection = url.openConnection() as HttpURLConnection
            connection.requestMethod = "GET"
            val content = connection.inputStream.bufferedReader().use { it.readText() }
            connection.disconnect()

            // Verify template elements
            assertTrue(content.contains("<!DOCTYPE html>"), "Should be HTML")
            assertTrue(content.contains("<title>Index of / - Klaat</title>"), "Should have correct title")
            assertTrue(content.contains("subdir/"), "Should list subdirectory")
            assertTrue(content.contains("test-file.txt"), "Should list file")
            assertTrue(content.contains("breadcrumb"), "Should have breadcrumb div")
            assertTrue(content.contains("Generated by Klaat Codelab Server"), "Should have footer")
            assertTrue(content.contains("Last Modified"), "Should have table headers")
            assertTrue(content.contains("material-symbols-outlined"), "Should have material symbols class")
            assertTrue(content.contains("folder"), "Should contain folder symbol")
            assertTrue(content.contains("description"), "Should contain description (file) symbol")
            assertTrue(content.contains("Space") && content.contains("Grotesk"), "Should use Space Grotesk font")
            assertTrue(content.contains("hero"), "Should have hero section")
            assertTrue(content.contains("nav"), "Should have nav section")
            assertTrue(content.contains("listing-card"), "Should have listing card")
            assertTrue(content.contains("kartikarora.1.7.0.css"), "Should use kartikarora CSS framework")
            assertTrue(content.contains("kartikarora.1.7.0.js"), "Should use kartikarora JS framework")

        } finally {
            serverThread?.interrupt()
            Thread.sleep(500)
        }
    }
}
